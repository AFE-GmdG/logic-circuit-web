export const MAX_HDL_TESTABLE_INPUT_BITS = 16;

// Gerichtete Verbindung zwischen zwei HDL-Symbolen inklusive Teilbit-Bereichen analog zu HdlConnection.cs
export type HdlConnectionNode = {
  outSymbol: HdlSymbolNode;
  outJam: Jam;
  outBits: HdlBitRange;
  inSymbol: HdlSymbolNode;
  inJam: Jam;
  inBits: HdlBitRange;
  skipOutput: boolean;
};

// Repräsentiert ein exportierbares Bauteil im HDL-Netzlistengraphen analog zu HdlSymbol.cs
export type HdlSymbolNode = {
  circuitSymbol: CircuitSymbol;
  connections: HdlConnectionNode[];
  order: number;
  autoGenerated: boolean;
  subindex?: number;
  comment?: string;
};

// Validierter und topologisch sortierter HDL-Schaltungsgraph analog zu HdlExport.cs
export type HdlCircuitGraph = {
  circuit: LogicalCircuit;
  project: CircuitProject;
  language: HdlExportLanguage;
  inputPins: HdlSymbolNode[];
  outputPins: HdlSymbolNode[];
  parts: HdlSymbolNode[];
  allSymbols: HdlSymbolNode[];
  logs: HdlLogEntry[];
  hasErrors: boolean;
};

export type BuildHdlGraphOptions = {
  checkUnconnectedInputs?: boolean;
  transformFn?: (graph: HdlCircuitGraph) => void;
};

// Erzeugt einen vollständigen Bit-Bereich [0..bitWidth-1]
export function createFullBitRange(bitWidth: number): HdlBitRange {
  return {
    first: 0,
    last: Math.max(0, bitWidth - 1),
  };
}

// Extrahiert den vorzeichenlosen Teilwert für einen Bit-Bereich [first..last] analog zu BitRange.Extract
export function extractBitRangeValue(value: number, range: HdlBitRange): number {
  const width = range.last - range.first + 1;
  if (width <= 0) {
    return 0;
  }
  const shifted = (value >>> range.first) >>> 0;
  if (width >= 32) {
    return shifted;
  }
  const mask = ((1 << width) - 1) >>> 0;
  return (shifted & mask) >>> 0;
}

// Prüft, ob sich zwei Bit-Bereiche überschneiden oder unmittelbar aneinander angrenzen
export function canMergeBitRange(a: HdlBitRange, b: HdlBitRange): boolean {
  return Math.max(a.first, b.first) - Math.min(a.last, b.last) <= 1;
}

// Verschmilzt zwei kompatible Bit-Bereiche zu einem zusammenhängenden Intervall
export function mergeBitRange(a: HdlBitRange, b: HdlBitRange): HdlBitRange {
  return {
    first: Math.min(a.first, b.first),
    last: Math.max(a.last, b.last),
  };
}

export function bitRangeEquals(a: HdlBitRange, b: HdlBitRange): boolean {
  return a.first === b.first && a.last === b.last;
}

function getHdlJamKey(jam: Jam): string {
  return `${jam.circuitSymbolId}:${jam.pin.pinId}`;
}

function createLogEntry(
  level: HdlLogLevel,
  code: HdlLogCode,
  circuitName: string,
  message: string,
  params?: Record<string, string | number>,
): HdlLogEntry {
  return {
    level,
    code,
    circuitName,
    message,
    params,
  };
}

function pushLog(
  graph: HdlCircuitGraph,
  level: HdlLogLevel,
  code: HdlLogCode,
  message: string,
  params?: Record<string, string | number>,
): void {
  graph.logs.push(createLogEntry(level, code, graph.circuit.name, message, params));
  if (level === "error") {
    graph.hasErrors = true;
  }
}

// Splitter und Probes werden beim HDL-Export aufgelöst bzw. ignoriert und nicht als Bauteile emittiert
export function isTransparentOrIgnoredHdlCircuit(circuit: Circuit): boolean {
  return circuit.kind === "splitter" || circuit.kind === "circuitProbe";
}

// Prüft, ob ein Bauteil in der gewählten HDL-Zielsprache exportiert werden kann analog zu CanExport
export function canExportCircuitComponent(circuit: Circuit, language: HdlExportLanguage): boolean {
  switch (circuit.kind) {
    case "logicalCircuit":
    case "pin":
    case "constant":
    case "memory":
      return true;
    case "gate": {
      const gate = circuit as Gate;
      if (gate.gateType === "clock" || gate.gateType === "led") {
        return false;
      }
      if (gate.gateType === "triState1" || gate.gateType === "triState2") {
        return language !== "n2t";
      }
      return (
        gate.gateType === "not" ||
        gate.gateType === "and" ||
        gate.gateType === "or" ||
        gate.gateType === "xor" ||
        gate.gateType === "nop"
      );
    }
    case "circuitButton":
    case "sensor":
    case "ledMatrix":
    case "sound":
    case "synthesizer":
    case "graphicsArray":
    default:
      return false;
  }
}

// Ermittelt für ein Pin-Symbol innerhalb einer LogicalCircuit die externe Richtung ("input" vs "output")
export function getPinSymbolDirection(symbol: CircuitSymbol): "input" | "output" {
  const internalPin = symbol.circuit.pins[0];
  return internalPin?.pinType === "output" ? "input" : "output";
}

// Liefert die Signalrichtung eines Jam unter Berücksichtigung eingebetteter Subcircuit-Pins
export function getHdlJamDirection(jam: Jam, ownerCircuit: Circuit | undefined): PinType {
  if (ownerCircuit?.kind === "logicalCircuit") {
    return jam.pin.pinType;
  }
  return jam.effectivePinType;
}

// Löst die zu exportierenden LogicalCircuits gemäß Scope in deterministischer Reihenfolge auf
export function resolveExportTargetCircuits(
  project: CircuitProject,
  currentCircuit: LogicalCircuit,
  scope: HdlExportScope,
): LogicalCircuit[] {
  const visited = new Set<string>();
  const result: LogicalCircuit[] = [];

  const collectWithEmbeddedSubcircuits = (root: LogicalCircuit): void => {
    if (visited.has(root.logicalCircuitId)) {
      return;
    }
    visited.add(root.logicalCircuitId);
    result.push(root);

    for (const symbol of root.circuitSymbols) {
      if (symbol.circuit.kind === "logicalCircuit") {
        const subcircuit = symbol.circuit as LogicalCircuit;
        collectWithEmbeddedSubcircuits(subcircuit);
      }
    }
  };

  if (scope === "current") {
    return [currentCircuit];
  }

  if (scope === "currentWithSubcircuits") {
    collectWithEmbeddedSubcircuits(currentCircuit);
    return result;
  }

  for (const lc of project.logicalCircuits) {
    if (lc.exportToHDL) {
      collectWithEmbeddedSubcircuits(lc);
    }
  }

  return result;
}

// Baut das rohe ConnectionSet einer einzelnen LogicalCircuit über alle elektrischen Leiter auf
function buildLocalConnectionSet(circuit: LogicalCircuit): ConnectionSet {
  const connectionSet = new ConnectionSet();
  const conductorMap = buildConductorMap(circuit.wires);

  const inJamMap = new Map<string, Jam[]>();
  for (const sym of circuit.circuitSymbols) {
    for (const jam of sym.jams) {
      if (getHdlJamDirection(jam, sym.circuit) !== "output") {
        const key = gridPointKey(jam.absolutePoint);
        let list = inJamMap.get(key);
        if (!list) {
          list = [];
          inJamMap.set(key, list);
        }
        list.push(jam);
      }
    }
  }

  for (const sym of circuit.circuitSymbols) {
    for (const outJam of sym.jams) {
      if (getHdlJamDirection(outJam, sym.circuit) === "input") {
        continue;
      }
      const outKey = gridPointKey(outJam.absolutePoint);
      const conductor = conductorMap.byPointKey.get(outKey);
      if (!conductor) {
        continue;
      }
      for (const pt of conductor.points) {
        const inList = inJamMap.get(gridPointKey(pt));
        if (!inList) {
          continue;
        }
        for (const inJam of inList) {
          if (inJam !== outJam) {
            connectionSet.connect(inJam, outJam);
          }
        }
      }
    }
  }

  return connectionSet;
}

// Erstellt eine volle oder bitweise zusammengeführte HdlConnectionNode analog zu HdlConnection.Create
function createFullHdlConnection(
  outSymbol: HdlSymbolNode,
  outJam: Jam,
  inSymbol: HdlSymbolNode,
  inJam: Jam,
): HdlConnectionNode {
  const conn: HdlConnectionNode = {
    outSymbol,
    outJam,
    outBits: createFullBitRange(outJam.pin.bitWidth),
    inSymbol,
    inJam,
    inBits: createFullBitRange(inJam.pin.bitWidth),
    skipOutput: false,
  };
  outSymbol.connections.push(conn);
  if (inSymbol !== outSymbol) {
    inSymbol.connections.push(conn);
  }
  return conn;
}

function connectSingleBitHdlConnection(
  outSymbol: HdlSymbolNode,
  outJam: Jam,
  outBit: number,
  inSymbol: HdlSymbolNode,
  inJam: Jam,
  inBit: number,
): HdlConnectionNode {
  let existing: HdlConnectionNode | null = null;
  for (let i = outSymbol.connections.length - 1; i >= 0; i--) {
    const c = outSymbol.connections[i];
    if (c && c.outJam === outJam && c.inJam === inJam) {
      existing = c;
      break;
    }
  }

  if (existing && existing.outBits.last + 1 === outBit && existing.inBits.last + 1 === inBit) {
    existing.outBits.last = outBit;
    existing.inBits.last = inBit;
    return existing;
  }

  const conn: HdlConnectionNode = {
    outSymbol,
    outJam,
    outBits: { first: outBit, last: outBit },
    inSymbol,
    inJam,
    inBits: { first: inBit, last: inBit },
    skipOutput: false,
  };
  outSymbol.connections.push(conn);
  if (inSymbol !== outSymbol) {
    inSymbol.connections.push(conn);
  }
  return conn;
}

// Sortiert die Verbindungen jedes Symbols (Eingänge vor Ausgängen) und markiert doppelte Ausgangsbereiche
export function sortSymbolConnections(symbols: HdlSymbolNode[]): void {
  for (const symbol of symbols) {
    symbol.connections.sort((a, b) => {
      const jamA = a.inSymbol === symbol ? a.inJam : a.outJam;
      const jamB = b.inSymbol === symbol ? b.inJam : b.outJam;

      const dirA = getHdlJamDirection(jamA, symbol.circuitSymbol.circuit);
      const dirB = getHdlJamDirection(jamB, symbol.circuitSymbol.circuit);

      if (dirA !== dirB) {
        return dirA === "input" ? -1 : 1;
      }

      const pinCmp = comparePins(jamA.pin, jamB.pin);
      if (pinCmp !== 0) {
        return pinCmp;
      }

      const bitsA = a.inSymbol === symbol ? a.inBits : a.outBits;
      const bitsB = b.inSymbol === symbol ? b.inBits : b.outBits;
      return bitsB.first - bitsA.first;
    });

    if (symbol.circuitSymbol.circuit.kind !== "pin") {
      for (const conn of symbol.connections) {
        if (conn.outSymbol === symbol) {
          conn.skipOutput = false;
        }
      }
      for (let i = 0; i < symbol.connections.length; i++) {
        const current = symbol.connections[i];
        if (
          !current ||
          current.outSymbol !== symbol ||
          current.inSymbol.circuitSymbol.circuit.kind === "pin"
        ) {
          continue;
        }
        for (let j = i - 1; j >= 0; j--) {
          const prev = symbol.connections[j];
          if (
            prev &&
            prev.outSymbol === symbol &&
            prev.inSymbol.circuitSymbol.circuit.kind !== "pin" &&
            prev.outJam === current.outJam &&
            bitRangeEquals(prev.outBits, current.outBits)
          ) {
            current.skipOutput = true;
            break;
          }
        }
      }
    }
  }
}

// Berechnet topologische Signalstufen ausgehend von Eingangs-Pins analog zu HdlExport.OrderSymbols
function orderHdlSymbols(symbol: HdlSymbolNode, onPath: Set<HdlSymbolNode>): void {
  for (const connection of symbol.connections) {
    if (connection.outJam.circuitSymbolId !== symbol.circuitSymbol.circuitSymbolId) {
      continue;
    }
    const other = connection.inSymbol;
    const nextOrder = symbol.order + 1;
    if (other !== symbol && !onPath.has(other) && nextOrder > other.order) {
      other.order = nextOrder;
      onPath.add(other);
      orderHdlSymbols(other, onPath);
      onPath.delete(other);
    }
  }
}

function buildPinSortMap(symbols: CircuitSymbol[]): Map<string, { x: number; y: number }> {
  const coords = new Map<string, { x: number; y: number }>();
  for (const sym of symbols) {
    if (sym.circuit.kind === "pin") {
      const point = { x: sym.x, y: sym.y };
      coords.set(sym.circuit.circuitId, point);
      coords.set(sym.circuitId, point);
    }
  }
  return coords;
}

function comparePinSymbols(a: HdlSymbolNode, b: HdlSymbolNode, coords: Map<string, { x: number; y: number }>): number {
  const pinA = a.circuitSymbol.circuit.pins[0];
  const pinB = b.circuitSymbol.circuit.pins[0];
  if (pinA && pinB) {
    const cmp = comparePins(pinA, pinB, coords);
    if (cmp !== 0) {
      return cmp;
    }
  }
  const dy = a.circuitSymbol.y - b.circuitSymbol.y;
  if (dy !== 0) {
    return dy;
  }
  return a.circuitSymbol.x - b.circuitSymbol.x;
}

// Prüft auf übereinanderliegende Anschlusspunkte sowie unbeschaltete / unvollständige Eingänge
function validateHdlCircuitGraph(graph: HdlCircuitGraph, checkUnconnectedInputs: boolean): void {
  const jamPoints = new Map<string, Jam>();

  const checkSymbolJams = (symbol: HdlSymbolNode): void => {
    for (const jam of symbol.circuitSymbol.jams) {
      const key = gridPointKey(jam.absolutePoint);
      if (jamPoints.has(key)) {
        pushLog(
          graph,
          "error",
          "jamsColocated",
          `Mehrere Anschlüsse liegen in '${graph.circuit.name}' an derselben Position (${jam.absolutePoint.x}, ${jam.absolutePoint.y}).`,
          { x: jam.absolutePoint.x, y: jam.absolutePoint.y },
        );
      } else {
        jamPoints.set(key, jam);
      }
    }
  };

  for (const pin of graph.inputPins) {
    checkSymbolJams(pin);
  }
  for (const pin of graph.outputPins) {
    checkSymbolJams(pin);
  }
  for (const part of graph.parts) {
    if (!part.autoGenerated) {
      checkSymbolJams(part);
    }
  }

  if (!checkUnconnectedInputs) {
    return;
  }

  const validateSymbolInputs = (symbol: HdlSymbolNode): void => {
    const inputJams = symbol.circuitSymbol.jams.filter(
      (j) => getHdlJamDirection(j, symbol.circuitSymbol.circuit) === "input",
    );
    for (const inputJam of inputJams) {
      const ranges: HdlBitRange[] = [];
      for (const conn of symbol.connections) {
        if (conn.inJam === inputJam) {
          ranges.push({ ...conn.inBits });
        }
      }

      if (ranges.length === 0) {
        pushLog(
          graph,
          "warning",
          "jamUnconnected",
          `Eingang '${inputJam.pin.name}' an Bauteil '${symbol.circuitSymbol.circuit.name}' in '${graph.circuit.name}' ist unbeschaltet.`,
          {
            pinName: inputJam.pin.name,
            symbolName: symbol.circuitSymbol.circuit.name,
          },
        );
        continue;
      }

      ranges.sort((a, b) => a.first - b.first);
      let merged = { ...ranges[0]! };
      for (let i = 1; i < ranges.length; i++) {
        const next = ranges[i]!;
        if (canMergeBitRange(merged, next)) {
          merged = mergeBitRange(merged, next);
        }
      }

      if (merged.first !== 0 || merged.last !== inputJam.pin.bitWidth - 1) {
        const rangeText = `[${merged.first}..${merged.last}]`;
        pushLog(
          graph,
          "warning",
          "inputNotFull",
          `Eingang '${inputJam.pin.name}' (${inputJam.pin.bitWidth} Bit) an '${symbol.circuitSymbol.circuit.name}' nur im Bereich ${rangeText} beschaltet.`,
          {
            pinName: inputJam.pin.name,
            bitWidth: inputJam.pin.bitWidth,
            symbolName: symbol.circuitSymbol.circuit.name,
          },
        );
      }
    }
  };

  for (const pin of graph.outputPins) {
    validateSymbolInputs(pin);
  }
  for (const part of graph.parts) {
    validateSymbolInputs(part);
  }
}

// Erstellt den vollständigen, aufgelösten HDL-Netzlistengraphen für einen LogicalCircuit
export function buildHdlCircuitGraph(
  circuit: LogicalCircuit,
  project: CircuitProject,
  language: HdlExportLanguage,
  options: BuildHdlGraphOptions = {},
): HdlCircuitGraph {
  const graph: HdlCircuitGraph = {
    circuit,
    project,
    language,
    inputPins: [],
    outputPins: [],
    parts: [],
    allSymbols: [],
    logs: [],
    hasErrors: false,
  };

  const symbolMap = new Map<string, HdlSymbolNode>();
  for (const sym of circuit.circuitSymbols) {
    if (isTransparentOrIgnoredHdlCircuit(sym.circuit)) {
      continue;
    }
    if (!canExportCircuitComponent(sym.circuit, language)) {
      pushLog(
        graph,
        "error",
        "circuitUnsupported",
        `Bauteil '${sym.circuit.name}' (${sym.circuit.kind ?? "unbekannt"}) wird im ${language.toUpperCase()}-Export nicht unterstützt.`,
        { symbolName: sym.circuit.name, language },
      );
      continue;
    }

    const node: HdlSymbolNode = {
      circuitSymbol: sym,
      connections: [],
      order: sym.circuit.kind === "pin" && getPinSymbolDirection(sym) === "input" ? 1 : 0,
      autoGenerated: false,
    };
    symbolMap.set(sym.circuitSymbolId, node);
  }

  if (graph.hasErrors) {
    return graph;
  }

  const connectionSet = buildLocalConnectionSet(circuit);
  const symbolById = new Map<string, CircuitSymbol>();
  for (const sym of circuit.circuitSymbols) {
    symbolById.set(sym.circuitSymbolId, sym);
  }

  for (const outSymbol of symbolMap.values()) {
    for (const outJam of outSymbol.circuitSymbol.jams) {
      if (getHdlJamDirection(outJam, outSymbol.circuitSymbol.circuit) === "input") {
        continue;
      }
      const connections = connectionSet.selectByOutput(outJam);
      for (const conn of connections) {
        const targetSym = symbolById.get(conn.inJam.circuitSymbolId);
        if (!targetSym) {
          continue;
        }

        if (targetSym.circuit.kind === "splitter") {
          for (let bit = 0; bit < outJam.pin.bitWidth; bit++) {
            const visited = new Set<string>();

            const propagateThroughSplitter = (enterJam: Jam, enterBit: number): void => {
              const visitKey = `${getHdlJamKey(enterJam)}:${enterBit}`;
              if (visited.has(visitKey)) {
                pushLog(
                  graph,
                  "error",
                  "loopInSplitter",
                  `Splitter-Zyklus erkannt in '${circuit.name}'.`,
                );
                return;
              }
              visited.add(visitKey);

              const splitterSym = symbolById.get(enterJam.circuitSymbolId);
              if (!splitterSym) {
                return;
              }
              const { exitJam, exitBit } = passSplitterBit(splitterSym.jams, enterJam, enterBit);
              const exitConnections = connectionSet.selectByOutput(exitJam);
              for (const nextConn of exitConnections) {
                const nextSym = symbolById.get(nextConn.inJam.circuitSymbolId);
                if (!nextSym) {
                  continue;
                }
                if (nextSym.circuit.kind === "splitter") {
                  propagateThroughSplitter(nextConn.inJam, exitBit);
                } else {
                  const inSymbol = symbolMap.get(nextSym.circuitSymbolId);
                  if (inSymbol) {
                    connectSingleBitHdlConnection(
                      outSymbol,
                      outJam,
                      bit,
                      inSymbol,
                      nextConn.inJam,
                      exitBit,
                    );
                  }
                }
              }
            };

            propagateThroughSplitter(conn.inJam, bit);
            if (graph.hasErrors) {
              break;
            }
          }
        } else {
          const inSymbol = symbolMap.get(targetSym.circuitSymbolId);
          if (inSymbol) {
            createFullHdlConnection(outSymbol, outJam, inSymbol, conn.inJam);
          }
        }

        if (graph.hasErrors) {
          break;
        }
      }
      if (graph.hasErrors) {
        break;
      }
    }
    if (graph.hasErrors) {
      break;
    }
  }

  if (graph.hasErrors) {
    return graph;
  }

  const pinCoords = buildPinSortMap(circuit.circuitSymbols);
  for (const node of symbolMap.values()) {
    const kind = node.circuitSymbol.circuit.kind;
    if (kind === "pin") {
      if (getPinSymbolDirection(node.circuitSymbol) === "input") {
        graph.inputPins.push(node);
      } else {
        graph.outputPins.push(node);
      }
    } else if (kind !== "constant") {
      graph.parts.push(node);
    }
    graph.allSymbols.push(node);
  }

  for (const inputPin of graph.inputPins) {
    const onPath = new Set<HdlSymbolNode>([inputPin]);
    orderHdlSymbols(inputPin, onPath);
  }

  graph.inputPins.sort((a, b) => comparePinSymbols(a, b, pinCoords));
  graph.outputPins.sort((a, b) => comparePinSymbols(a, b, pinCoords));
  graph.parts.sort(
    (a, b) =>
      a.order - b.order ||
      a.circuitSymbol.y - b.circuitSymbol.y ||
      a.circuitSymbol.x - b.circuitSymbol.x,
  );

  if (options.transformFn) {
    options.transformFn(graph);
  }

  sortSymbolConnections([...graph.inputPins, ...graph.outputPins, ...graph.parts]);
  validateHdlCircuitGraph(graph, options.checkUnconnectedInputs ?? true);

  return graph;
}

// Berechnet Testvektoren aus der vollständigen Wahrheitstabelle bis maximal maxInputBits Eingangs-Bits
export function buildHdlTruthTableVectors(
  circuit: LogicalCircuit,
  project: CircuitProject,
  maxInputBits = MAX_HDL_TESTABLE_INPUT_BITS,
  maxRows = DEFAULT_MAX_TRUTH_TABLE_ROWS,
): HdlTruthTableVectors {
  if (!isTestable(circuit, project)) {
    return {
      status: "notTestable",
      inputs: [],
      outputs: [],
      rows: [],
      totalInputBits: 0,
    };
  }

  const socket = new CircuitTestSocket(circuit, project);
  const inputInfos: HdlTruthTablePinInfo[] = socket.inputs.map((inp) => ({
    symbolId: inp.symbol.circuitSymbolId,
    pinId: inp.pin.pinId,
    name: inp.pin.name,
    bitWidth: inp.pin.bitWidth,
  }));
  const outputInfos: HdlTruthTablePinInfo[] = socket.outputs.map((out) => ({
    symbolId: out.symbol.circuitSymbolId,
    pinId: out.pin.pinId,
    name: out.pin.name,
    bitWidth: out.pin.bitWidth,
  }));
  const totalInputBits = socket.inputBitCount;

  if (totalInputBits > maxInputBits) {
    return {
      status: "inputTooBig",
      inputs: inputInfos,
      outputs: outputInfos,
      rows: [],
      totalInputBits,
    };
  }

  try {
    const result = socket.buildTruthTable({ maxCount: maxRows });
    if (result.oscillation || result.rows === null) {
      return {
        status: "oscillation",
        inputs: inputInfos,
        outputs: outputInfos,
        rows: [],
        totalInputBits,
      };
    }

    if (result.truncated) {
      return {
        status: "truncated",
        inputs: inputInfos,
        outputs: outputInfos,
        rows: result.rows.map((r) => ({
          inputs: [...r.input],
          outputs: r.output ? [...r.output] : null,
          rawStates: r.rawStates.map((bits) => [...bits]),
        })),
        totalInputBits,
      };
    }

    return {
      status: "ok",
      inputs: inputInfos,
      outputs: outputInfos,
      rows: result.rows.map((r) => ({
        inputs: [...r.input],
        outputs: r.output ? [...r.output] : null,
        rawStates: r.rawStates.map((bits) => [...bits]),
      })),
      totalInputBits,
    };
  } catch (error) {
    return {
      status: "error",
      inputs: inputInfos,
      outputs: outputInfos,
      rows: [],
      totalInputBits,
      errorMessage: error instanceof Error ? error.message : String(error),
    };
  }
}
